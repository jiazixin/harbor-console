type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (source: string) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

function initialLocale(): Locale {
  return readStoredItem("localStorage", storageKey) === "en-US"
    ? "en-US"
    : "zh-CN";
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, updateLocale] = useState<Locale>(initialLocale);
  const setLocale = useCallback((next: Locale) => {
    document.documentElement.classList.add("language-reload-in");
    writeStoredItem("localStorage", storageKey, next);
    updateLocale(next);
    window.setTimeout(
      () => document.documentElement.classList.remove("language-reload-in"),
      340,
    );
  }, []);
  const t = useCallback(
    (source: string) =>
      locale === "en-US" ? (english.get(source) ?? source) : source,
    [locale],
  );

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo(
    () => ({ locale, setLocale, t }),
    [locale, setLocale, t],
  );
  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used within LocaleProvider");
  return value;
}
