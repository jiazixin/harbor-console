  function translate(value) {
    const source = String(value ?? "");
    if (language !== "en-US" || !/[\u3400-\u9fff]/.test(source)) return source;
    const leading = source.match(/^\s*/)?.[0] || "";
    const trailing = source.match(/\s*$/)?.[0] || "";
    const core = source.trim();
    if (!core) return source;
    const direct = exact.get(core);
    if (direct) return `${leading}${direct}${trailing}`;
    const patterned = translatePattern(core);
    if (patterned) return `${leading}${patterned}${trailing}`;
    return source;
  }

  function shouldSkip(node) {
    const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
    return !element || Boolean(element.closest(rawSelector));
  }

  function translateElement(element) {
    if (!(element instanceof Element) || shouldSkip(element)) return;
    for (const attribute of ["placeholder", "title", "aria-label"]) {
      if (!element.hasAttribute(attribute)) continue;
      const current = element.getAttribute(attribute);
      const translated = translate(current);
      if (translated !== current) element.setAttribute(attribute, translated);
    }
    for (const node of element.childNodes) {
      if (node.nodeType !== Node.TEXT_NODE || shouldSkip(node)) continue;
      const translated = translate(node.nodeValue);
      if (translated !== node.nodeValue) node.nodeValue = translated;
    }
  }

  function apply(root = document) {
    document.documentElement.lang = language;
    if (root === document) document.title = language === "en-US" ? translate("Harbor 控制台") : "Harbor 控制台";
    if (root.nodeType === Node.ELEMENT_NODE) translateElement(root);
    const scope = root.querySelectorAll ? root : document;
    const selector = root === document ? "body *, title" : "*";
    for (const element of scope.querySelectorAll(selector)) translateElement(element);
    updateSwitches();
  }

  function flush() {
    frame = 0;
    const roots = [...pendingRoots];
    pendingRoots = new Set();
    for (const root of roots) apply(root);
  }

  function queue(root) {
    if (!root || shouldSkip(root)) return;
    pendingRoots.add(root.nodeType === Node.TEXT_NODE ? root.parentElement : root);
    if (!frame) frame = requestAnimationFrame(flush);
  }

  function updateSwitches() {
    for (const group of document.querySelectorAll(".language-switch")) {
      group.setAttribute("aria-label", language === "en-US" ? "Interface language" : "界面语言");
    }
    for (const button of document.querySelectorAll("[data-language]")) {
      const active = button.dataset.language === language;
      button.classList.toggle("active", active);
      button.setAttribute("aria-pressed", String(active));
      if (button.dataset.language === "zh-CN") button.setAttribute("aria-label", language === "en-US" ? "Switch to Chinese" : "切换为中文");
    }
  }

  function setLanguage(next) {
    if (!supported.has(next) || next === language) return;
    window.dispatchEvent(new Event("harbor:before-language-reload"));
    localStorage.setItem(storageKey, next);
    location.reload();
  }

  function untranslated(root = document) {
    const values = new Set();
    const scope = root.querySelectorAll ? root : document;
    for (const element of scope.querySelectorAll("body *")) {
      if (shouldSkip(element)) continue;
      for (const node of element.childNodes) {
        if (node.nodeType === Node.TEXT_NODE && /[\u3400-\u9fff]/.test(node.nodeValue || "")) values.add(node.nodeValue.trim());
      }
      for (const attribute of ["placeholder", "title", "aria-label"]) {
        const value = element.getAttribute(attribute);
        if (value && /[\u3400-\u9fff]/.test(value)) values.add(value);
      }
    }
    return [...values].filter(Boolean).sort();
  }

  function init() {
    apply(document);
    document.addEventListener("click", (event) => {
      const button = event.target.closest("[data-language]");
      if (button) setLanguage(button.dataset.language);
    });
    observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) for (const node of mutation.addedNodes) queue(node);
    });
    observer.observe(document.body, { childList: true, subtree: true });
  }

  window.HarborI18n = {
    apply,
    language: () => language,
    locale: () => language,
    setLanguage,
    translate,
    untranslated,
  };

  init();
